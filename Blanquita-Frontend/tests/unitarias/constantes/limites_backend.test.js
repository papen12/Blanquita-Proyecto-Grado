describe('los límites del frontend son espejo de Cantidades.py', () => {
  it.each(Object.entries(EQUIVALENCIAS))('%s = %s', (front, back) => {
    expect(CANTIDADES[back], `${back} no existe en Cantidades.py`).toBeDefined();
    expect(Values[front]).toBe(CANTIDADES[back]);
  });

  it('las claves coinciden con Security.py', () => {
    expect(Values.CLAVE_MIN).toBe(SEGURIDAD.LONGITUD_MINIMA);
    expect(Values.CLAVE_MAX).toBe(SEGURIDAD.LONGITUD_MAXIMA);
  });

  it('la hora límite del conteo coincide con Horario.py', () => {
    const horario = readFileSync(resolve(BACKEND, 'Constants/Horario.py'), 'utf8');

    expect(horario).toMatch(new RegExp(`HORA_LIMITE_INICIO_CONTEO = time\\(${Values.HORA_LIMITE_INICIO_CONTEO}, 0, 0\\)`));
  });
});

describe('rangos normales del aviso de confirmación', () => {
  it.each([
    ['PESO_BRUTO_NORMAL_BOBINA_PAPEL_KG', 'PESO_BRUTO_MINIMO_BOBINA_PAPEL_KG', 'PESO_BRUTO_MAXIMO_BOBINA_PAPEL_KG'],
    ['PESO_NORMAL_UNIDAD_SERVILLETA_KG', 'PESO_MINIMO_UNIDAD_SERVILLETA_KG', 'PESO_MAXIMO_UNIDAD_SERVILLETA_KG'],
    ['PESO_NORMAL_EMPAQUE_BOBINA_KG', 'PESO_MINIMO_EMPAQUE_BOBINA_KG', 'PESO_MAXIMO_EMPAQUE_BOBINA_KG'],
    ['TONELADAS_NORMALES_PEDIDO', 'TONELADAS_MINIMAS_PEDIDO', 'TONELADAS_MAXIMAS_PEDIDO'],
  ])('%s queda dentro del límite duro', (normal, minimo, maximo) => {
    const [desde, hasta] = Values[normal];

    expect(desde).toBeLessThan(hasta);
    expect(desde).toBeGreaterThanOrEqual(Values[minimo]);
    expect(hasta).toBeLessThanOrEqual(Values[maximo]);
  });

  it('la tara normal queda bajo la tara máxima', () => {
    expect(Values.TARA_NORMAL_BOBINA_KG[1]).toBeLessThanOrEqual(Values.TARA_MAXIMA_BOBINA_KG);
  });
});

describe('roles y rutas', () => {
  it('cada rol tiene prefijo y ruta de inicio coherentes', () => {
    Object.values(Values.Roles).forEach((id) => {
      expect(Values.RUTA_POR_ROL[id]).toBe(`/${Values.PREFIJO_POR_ROL[id]}/inicio`);
    });
  });

  it('los ids de rol coinciden con Roles.py', () => {
    const roles = leerConstantes('Constants/Roles.py');

    expect(Values.Roles).toEqual({
      Operador: roles.ROL_OPERADOR,
      Encargado: roles.ROL_LIDER_INVENTARIO_PRODUCCION,
      Gerente: roles.ROL_GERENTE_GENERAL,
    });
  });
});
